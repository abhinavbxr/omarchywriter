def init_user_config(cfg_path: Path | None = None, clr_path: Path | None = None) -> None:
    """Create only OmarchyWriter's own editable files when absent."""
    cfg_path, clr_path = cfg_path or get_config_path(), clr_path or get_colors_path()
    cfg_path.parent.mkdir(parents=True, exist_ok=True)
    if not cfg_path.exists():
        cfg_path.write_text(CONFIG_DEFAULTS, encoding="utf-8")
    if not clr_path.exists():
        clr_path.write_text(COLOR_DEFAULTS, encoding="utf-8")


def load_config(path: Path) -> Config:
    return Config.from_toml(path)


def load_colors(path: Path) -> ColorSet:
    return ColorSet.from_toml(path)


